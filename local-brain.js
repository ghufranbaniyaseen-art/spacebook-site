// ترتيب محلي بدون أي استدعاء خارجي
function rankLocally(books, answers){
  return books.map(b=>{
    let sc=0;
    const r=Number(b.rating)||0;
    if(answers[2]==='rated') sc += r*2;
    if(answers[2]==='cheap') sc += (10-Math.min(b.price,10));
    if(answers[0]==='short') sc += (10-Math.min(b.price,10))*0.4;
    sc += r;
    return {b,sc};
  }).sort((x,y)=>y.sc-x.sc).map(x=>x.b);
}
