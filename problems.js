// اختيار 9: كل أسبوع بتتبدل 3، وكل يوم الترتيب بيتغير
function pickProblems(){
  const day=Math.floor(Date.now()/864e5);
  const week=Math.floor(day/7);
  const start=(week*3)%PROBLEMS.length;
  const nine=[];
  for(let i=0;i<9;i++) nine.push(PROBLEMS[(start+i)%PROBLEMS.length]);
  // خلط يومي ثابت (نفس الترتيب لكل الزوار بنفس اليوم)
  let seed=day;
  const rnd=()=>{ seed=(seed*1103515245+12345)&0x7fffffff; return seed/0x7fffffff; };
  for(let i=nine.length-1;i>0;i--){
    const j=Math.floor(rnd()*(i+1));
    [nine[i],nine[j]]=[nine[j],nine[i]];
  }
  return nine;
}

