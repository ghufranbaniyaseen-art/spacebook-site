/* عرض عام: شبكة بوكسات + صندوق تفاصيل تحتها */
function mountTiles(gridId, detailId, items, label, body){
  const grid=document.getElementById(gridId), detail=document.getElementById(detailId);
  if(!grid||!detail) return;
  grid.innerHTML=items.map((it,i)=>
    `<button type="button" class="tile" data-i="${i}"><span>${esc(label(it))}</span></button>`).join('');
  grid.addEventListener('click',e=>{
    const t=e.target.closest('.tile'); if(!t) return;
    const i=Number(t.dataset.i);
    const wasOn=t.classList.contains('on');
    grid.querySelectorAll('.tile').forEach(x=>x.classList.remove('on'));
    if(wasOn){ detail.classList.remove('on'); return; }
    t.classList.add('on');
    detail.innerHTML=body(items[i]);
    detail.classList.add('on');
  });
}

